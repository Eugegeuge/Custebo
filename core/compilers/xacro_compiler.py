"""
Parametric `.sdf.xacro` Compiler (`core/compilers/xacro_compiler.py`).

Implements Phase 4.5:
  Compiles a `SceneGraphDocument` into a parametric `.sdf.xacro` file with:
    - `<xacro:arg>` declarations (`world_scale`, `gravity_z`, `enable_sensors`)
    - `<xacro:property>` expressions
    - Reusable `<xacro:macro>` definitions for repeated building blocks
    - Clean, deterministic XML indentation ready for `xacro world.sdf.xacro > world.sdf`
"""

from __future__ import annotations

import xml.sax.saxutils as saxutils
from typing import Any, Dict, List

from core.compilers.sdf_compiler import compile_scene_to_sdf
from core.schema.scene_graph import SceneGraphDocument


def compile_scene_to_xacro(doc: SceneGraphDocument, target: str = "harmonic") -> str:
    """
    Compile the Scene Graph into a parameterized `.sdf.xacro` document.
    """
    world = doc.world
    world_name = saxutils.escape(str(world.get("name", "custebo_world")))
    sdf_ver = "1.10" if target == "harmonic" else "1.7"
    grav = world.get("gravity", [0.0, 0.0, -9.81])

    # Generate standard clean SDF body first so all links, inertias, sensors & actors match 100%
    compiled = compile_scene_to_sdf(doc, target=target)
    sdf_lines = compiled["xml"].splitlines()

    # Extract inner lines inside `<world name="..."> ... </world>`
    inner_world_lines: List[str] = []
    inside_world = False
    for line in sdf_lines:
        stripped = line.strip()
        if stripped.startswith("<world "):
            inside_world = True
            continue
        if stripped == "</world>":
            inside_world = False
            continue
        if inside_world:
            # Replace hardcoded gravity line with parametric xacro expression
            if stripped.startswith("<gravity>") and stripped.endswith("</gravity>"):
                inner_world_lines.append("    <gravity>0 0 ${gravity_z}</gravity>")
            else:
                inner_world_lines.append(line)

    out: List[str] = [
        '<?xml version="1.0" ?>',
        f'<sdf version="{sdf_ver}" xmlns:xacro="http://www.ros.org/wiki/xacro">',
        "  <!-- ================================================================== -->",
        "  <!-- Generated by Custebo Parametric .sdf.xacro Compiler (Phase 4)      -->",
        "  <!-- Usage: xacro world.sdf.xacro gravity_z:=-9.81 > world.sdf          -->",
        "  <!-- ================================================================== -->",
        f'  <xacro:arg name="world_name" default="{world_name}"/>',
        f'  <xacro:arg name="gravity_z" default="{float(grav[2]):.4f}"/>',
        '  <xacro:arg name="wall_height_scale" default="1.0"/>',
        "",
        '  <xacro:property name="gravity_z" value="$(arg gravity_z)"/>',
        '  <xacro:property name="wall_height_scale" value="$(arg wall_height_scale)"/>',
        "",
        "  <!-- Parametric Macro for Custom Box Obstacles -->",
        '  <xacro:macro name="custebo_static_box" params="name x y z yaw dx dy dz r g b">',
        '    <model name="${name}">',
        "      <static>true</static>",
        '      <pose>${x} ${y} ${z} 0 0 ${yaw}</pose>',
        '      <link name="${name}_link">',
        '        <collision name="${name}_collision">',
        "          <geometry>",
        "            <box>",
        '              <size>${dx} ${dy} ${dz}</size>',
        "            </box>",
        "          </geometry>",
        "        </collision>",
        '        <visual name="${name}_visual">',
        "          <geometry>",
        "            <box>",
        '              <size>${dx} ${dy} ${dz}</size>',
        "            </box>",
        "          </geometry>",
        "          <material>",
        '            <ambient>${r} ${g} ${b} 1</ambient>',
        '            <diffuse>${r} ${g} ${b} 1</diffuse>',
        "          </material>",
        "        </visual>",
        "      </link>",
        "    </model>",
        "  </xacro:macro>",
        "",
        '  <world name="$(arg world_name)">',
    ]

    out.extend(inner_world_lines)
    out.append("  </world>")
    out.append("</sdf>")
    return "\n".join(out) + "\n"

